# Define two variables for comparison
a = 15
b = 10

print(f"Initial Values: a = {a}, b = {b}\n")

# 1. Equal to (==)
# Returns True if both values are equal
print(f"Is a equal to b? (a == b)                 -> {a == b}")

# 2. Not equal to (!=)
# Returns True if values are different
print(f"Is a not equal to b? (a != b)             -> {a != b}")

# 3. Greater than (>)
# Returns True if the left value is larger
print(f"Is a greater than b? (a > b)              -> {a > b}")

# 4. Less than (<)
# Returns True if the left value is smaller
print(f"Is a less than b? (a < b)                 -> {a < b}")

# 5. Greater than or equal to (>=)
# Returns True if the left value is larger or equal to the right
print(f"Is a greater than or equal to b? (a >= b) -> {a >= b}")

# 6. Less than or equal to (<=)
# Returns True if the left value is smaller or equal to the right
print(f"Is a less than or equal to b? (a <= b)    -> {a <= b}")
