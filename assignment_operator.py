# 1. Basic Assignment (=)
# Assigns a value to a variable
score = 10
print(f"Initial score: {score}")

# 2. Add and Assign (+=)
# Same as: score = score + 5
score += 5
print(f"After score += 5: {score}")

# 3. Subtract and Assign (-=)
# Same as: score = score - 3
score -= 3
print(f"After score -= 3: {score}")

# 4. Multiply and Assign (*=)
# Same as: score = score * 2
score *= 2
print(f"After score *= 2: {score}")

# 5. Divide and Assign (/=)
# Same as: score = score / 4 (converts the number to a decimal/float)
score /= 4
print(f"After score /= 4: {score}")
